import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.metrics import (
    confusion_matrix,
    classification_report,
    precision_recall_fscore_support
)

import torch


@torch.no_grad()
def evaluate_model(model, loader, class_names, device, weight_name="best_model.pth"):

    print("\n==========================")
    print("Evaluation")
    print("==========================")

    weight_path = os.path.join(CFG.MODEL_DIR, weight_name)

    if os.path.exists(weight_path):
        model.load_state_dict(torch.load(weight_path, map_location=device))
        print(f"Loaded : {weight_name}")
    else:
        print("Best model not found. Evaluating current model.")

    model.eval()

    y_true = []
    y_pred = []

    for images, labels in loader:

        images = images.to(device)
        outputs = model(images)

        preds = outputs.argmax(1).cpu().numpy()

        y_pred.extend(preds.tolist())
        y_true.extend(labels.numpy().tolist())

    labels_idx = list(range(len(class_names)))

    cm = confusion_matrix(
        y_true,
        y_pred,
        labels=labels_idx
    )

    # ----------------------------------------------------
    # Character Accuracy
    # ----------------------------------------------------

    class_acc = []

    for i in range(len(class_names)):
        total = cm[i].sum()

        acc = 0 if total == 0 else cm[i, i] / total

        class_acc.append(acc)

    acc_df = pd.DataFrame({
        "Character": class_names,
        "Accuracy": np.round(np.array(class_acc) * 100, 2)
    })

    acc_df.to_csv(
        os.path.join(CFG.EVAL_DIR, "class_accuracy.csv"),
        index=False,
        encoding="utf-8-sig"
    )

    print("\nCharacter Accuracy")
    print(acc_df)

    # ----------------------------------------------------
    # Precision / Recall / F1
    # ----------------------------------------------------

    precision, recall, f1, support = precision_recall_fscore_support(
        y_true,
        y_pred,
        labels=labels_idx,
        zero_division=0
    )

    metric_df = pd.DataFrame({
        "Character": class_names,
        "Support": support,
        "Precision": np.round(precision, 4),
        "Recall": np.round(recall, 4),
        "F1": np.round(f1, 4)
    })

    metric_df.to_csv(
        os.path.join(CFG.EVAL_DIR, "class_metrics.csv"),
        index=False,
        encoding="utf-8-sig"
    )

    # ----------------------------------------------------
    # Classification Report
    # ----------------------------------------------------

    report = classification_report(
        y_true,
        y_pred,
        target_names=class_names,
        labels=labels_idx,
        output_dict=True,
        zero_division=0
    )

    report_df = pd.DataFrame(report).transpose()

    report_df.to_csv(
        os.path.join(CFG.EVAL_DIR, "classification_report.csv"),
        encoding="utf-8-sig"
    )

    # ----------------------------------------------------
    # Confusion Matrix CSV
    # ----------------------------------------------------

    cm_df = pd.DataFrame(
        cm,
        index=class_names,
        columns=class_names
    )

    cm_df.to_csv(
        os.path.join(CFG.EVAL_DIR, "confusion_matrix.csv"),
        encoding="utf-8-sig"
    )

    # ----------------------------------------------------
    # Confusion Matrix PNG
    # ----------------------------------------------------

    fig_size = max(8, len(class_names))

    plt.figure(figsize=(fig_size, fig_size))
    plt.imshow(cm, cmap="Blues")
    plt.title("Confusion Matrix")
    plt.colorbar()

    plt.xticks(range(len(class_names)), class_names, rotation=90)
    plt.yticks(range(len(class_names)), class_names)

    plt.xlabel("Predicted")
    plt.ylabel("True")

    for i in range(len(class_names)):
        for j in range(len(class_names)):
            plt.text(
                j,
                i,
                str(cm[i, j]),
                ha="center",
                va="center",
                fontsize=8
            )

    plt.tight_layout()

    plt.savefig(
        os.path.join(CFG.EVAL_DIR, "confusion_matrix.png"),
        dpi=300
    )

    plt.close()

    # ----------------------------------------------------
    # Most Confused Character
    # ----------------------------------------------------

    confused = []

    print("\nMost Confused Character")

    for i in range(len(class_names)):

        row = cm[i].copy()
        row[i] = 0

        if row.sum() == 0:
            target = "-"
            count = 0
        else:
            idx = int(np.argmax(row))
            target = class_names[idx]
            count = int(row[idx])

        confused.append({
            "Character": class_names[i],
            "Most Confused": target,
            "Count": count
        })

        print(f"{class_names[i]} -> {target} ({count})")

    confused_df = pd.DataFrame(confused)

    confused_df.to_csv(
        os.path.join(CFG.EVAL_DIR, "confused_character.csv"),
        index=False,
        encoding="utf-8-sig"
    )

    overall = (np.array(y_true) == np.array(y_pred)).mean() * 100

    print("\n===================================")
    print(f"Overall Accuracy : {overall:.2f}%")
    print("Evaluation Complete")
    print("===================================")

