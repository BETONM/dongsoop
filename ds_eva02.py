# ==========================================================
# EarlyStopping
# ==========================================================

class EarlyStopping:

    def __init__(self, patience=5):
        self.patience = patience
        self.best_acc = 0.0
        self.counter = 0

    def step(self, val_acc):
        if val_acc > self.best_acc:
            self.best_acc = val_acc
            self.counter = 0
            return False, True

        self.counter += 1
        return self.counter >= self.patience, False


# ==========================================================
# Train / Validation
# ==========================================================

def train_one_epoch(model, loader, criterion, optimizer, device):

    model.train()

    total_loss = 0.0
    correct = 0
    total = 0

    for images, labels in loader:

        images = images.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True)

        optimizer.zero_grad()

        outputs = model(images)

        loss = criterion(outputs, labels)

        loss.backward()

        optimizer.step()

        total_loss += loss.item() * images.size(0)

        pred = outputs.argmax(1)

        correct += (pred == labels).sum().item()

        total += labels.size(0)

    return total_loss / total, 100 * correct / total


@torch.no_grad()
def validate_one_epoch(model, loader, criterion, device):

    model.eval()

    total_loss = 0.0
    correct = 0
    total = 0

    for images, labels in loader:

        images = images.to(device, non_blocking=True)
        labels = labels.to(device, non_blocking=True)

        outputs = model(images)

        loss = criterion(outputs, labels)

        total_loss += loss.item() * images.size(0)

        pred = outputs.argmax(1)

        correct += (pred == labels).sum().item()

        total += labels.size(0)

    return total_loss / total, 100 * correct / total


# ==========================================================
# Main Train Function
# ==========================================================

def train_model(
        model,
        train_loader,
        val_loader,
        optimizer,
        scheduler,
        device,
        epochs,
        save_name,
        log_name):

    criterion = nn.CrossEntropyLoss(
        label_smoothing=CFG.LABEL_SMOOTHING
    )

    logger = CSVLogger(
        os.path.join(CFG.LOG_DIR, log_name),
        [
            "Epoch",
            "Train Loss",
            "Train Acc",
            "Val Loss",
            "Val Acc",
            "LR"
        ]
    )

    stopper = EarlyStopping(CFG.PATIENCE)

    best_acc = 0.0

    for epoch in range(epochs):

        start = time.time()

        train_loss, train_acc = train_one_epoch(
            model,
            train_loader,
            criterion,
            optimizer,
            device
        )

        val_loss, val_acc = validate_one_epoch(
            model,
            val_loader,
            criterion,
            device
        )

        scheduler.step()

        lr = optimizer.param_groups[0]["lr"]

        logger.write([
            epoch + 1,
            round(train_loss, 5),
            round(train_acc, 2),
            round(val_loss, 5),
            round(val_acc, 2),
            lr
        ])

        print(
            f"Epoch [{epoch+1}/{epochs}] "
            f"| Train {train_loss:.4f}/{train_acc:.2f}% "
            f"| Val {val_loss:.4f}/{val_acc:.2f}% "
            f"| LR {lr:.2e} "
            f"| {time.time()-start:.0f}s"
        )

        stop, improved = stopper.step(val_acc)

        if improved:
            torch.save(
                model.state_dict(),
                os.path.join(CFG.MODEL_DIR, save_name)
            )

            best_acc = val_acc

            print("✓ Best Model Saved")

        if stop:
            print("Early Stopping")
            break

    print(f"\nBest Validation Accuracy : {best_acc:.2f}%")

    return model


# ==========================================================
# STEP1
# ==========================================================

def run_step1(model, train_loader, val_loader, device):

    print("\n===== STEP1 =====")

    for p in model.parameters():
        p.requires_grad = False

    for p in model.head.parameters():
        p.requires_grad = True

    optimizer = optim.AdamW(
        model.head.parameters(),
        lr=CFG.STEP1_LR,
        weight_decay=CFG.WEIGHT_DECAY
    )

    scheduler = optim.lr_scheduler.CosineAnnealingLR(
        optimizer,
        T_max=CFG.STEP1_EPOCHS
    )

    train_model(
        model,
        train_loader,
        val_loader,
        optimizer,
        scheduler,
        device,
        CFG.STEP1_EPOCHS,
        "step1_best.pth",
        "step1_log.csv"
    )


# ==========================================================
# STEP2
# ==========================================================

def run_step2(model, train_loader, val_loader, device):

    print("\n===== STEP2 =====")

  # ---------------------------------------
  # 1. 모든 파라미터 동결
  # ---------------------------------------
    for p in model.parameters():
        p.requires_grad = False

  # ---------------------------------------
  # 2. Head는 학습
  # ---------------------------------------

    for p in model.head.parameters():
        p.requires_grad = True

  # ---------------------------------------
  # 3. 마지막에 Transformer Block만 학습
  # ---------------------------------------
    for p in model.blocks[-1].parameters():
        p.requires_grad = True

    optimizer = optim.AdamW(
        filter(lambda p: p.requires_grad, model.parameters()),
        lr=CFG.STEP2_LR,
        weight_decay=CFG.WEIGHT_DECAY
    )

    scheduler = optim.lr_scheduler.CosineAnnealingLR(
        optimizer,
        T_max=CFG.STEP2_EPOCHS
    )

    train_model(
        model,
        train_loader,
        val_loader,
        optimizer,
        scheduler,
        device,
        CFG.STEP2_EPOCHS,
        "best_model.pth",
        "step2_log.csv"
    )

