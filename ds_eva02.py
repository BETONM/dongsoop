class CSVLogger:
    def __init__(self, filename, header):
        self.filename = filename

        with open(filename, "w", newline="", encoding="utf-8-sig") as f:
            writer = csv.writer(f)
            writer.writerow(header)
    def write(self, row):
        with open(self.filename, "a", newline="", encoding="utf-8-sig") as f:
            writer = csv.writer(f)
            writer.writerow(row)


